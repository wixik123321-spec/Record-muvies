def build():
    shots, n = [], 0
    for sec, card, mood in SECTIONS:
        for line in S[sec]:
            n += 1
            shots.append({"id": n, "section": sec, "section_title": card, "mood": mood, **line})
    out = ROOT / "build"
    out.mkdir(exist_ok=True)
    (out / "shots.json").write_text(json.dumps({"assets": ASSETS, "sections": SECTIONS, "shots": shots},
                                               ensure_ascii=False, indent=1), encoding="utf-8")
    # озвучка: разделы через пустую строку
    paras = []
    for sec, _, _ in SECTIONS:
        paras.append(" ".join(l["text"] for l in S[sec]))
    (ROOT / "script_voiceover.txt").write_text("\n\n".join(paras) + "\n", encoding="utf-8")
    # раскадровка
    rows = ["# Раскадровка: «Что если бы ИИ заменил всех людей на работе?»", "",
            "| № | Строка озвучки | Что на экране | Надпись на экране |", "|---|---|---|---|"]
    for s in shots:
        v = s["visual"]
        if v == "card":
            what = f"Заставка раздела «{s['section_title']}» (неон, глитч)"
            label = s["section_title"]
        elif isinstance(v, str):
            what = f"Фото: {ASSETS[v[4:]]} (Ken Burns)"
            label = s["onscreen"]
        else:
            kinds = {"list": "Инфографика-список", "counter": "Анимированный счётчик", "bars": "Анимированная диаграмма",
                     "timeline": "Таймлайн", "bigtext": "Крупный текст", "factcard": "Карточка фактов на фоне фото",
                     "chart_down": "Падающий график", "split": "Экран делится: утопия / антиутопия",
                     "endcard": "Конечная заставка с кнопкой подписки"}
            what = kinds.get(v["kind"], v["kind"])
            label = v.get("title") or v.get("text") or v.get("label") or s["onscreen"]
        rows.append(f"| {s['id']} | {s['text']} | {what} | {label} |")
    (ROOT / "storyboard.md").write_text("\n".join(rows) + "\n", encoding="utf-8")
    words = sum(len(s["text"].split()) for s in shots)
    chars = sum(len(s["text"]) for s in shots)
    print(f"{len(shots)} кадров, {words} слов, {chars} символов")


if __name__ == "__main__":
    build()
